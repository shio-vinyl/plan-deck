"""README 示例页：江屿市北岸老城（虚构项目），数字都是编的。

用法（在仓库根目录）：
    PYTHONPATH=src .venv/bin/python examples/sample_deck.py examples/style.json /tmp/sample.pptx
    .venv/bin/python bin/plan-deck render /tmp/sample.pptx --out /tmp/renders --engine libreoffice --style examples/style.json
"""
import sys

from plan_deck import Deck

style, out = sys.argv[1], sys.argv[2]
deck = Deck(style)
st = deck.style
x0, y0, x1, y1 = st.body
y0 += 0.5

# 1. 图文二分：现状用地
p = deck.page('evidence', '2.1 现状用地', parent='二、现状评估与问题识别')
p.conclusion('居住用地占四成，老旧小区和城中村集中在北岸沿江一线')
x, w = st.col(0, 5)
box = p.text(x, y0, w, [
    ('h', '用地构成'),
    '**总体判断：**片区总面积 **284.6 公顷**，现状建设用地 **251.2 公顷**，以居住用地为主，公共服务和绿地开敞空间不足。',
    '**居住用地：**112.4 公顷，其中 2000 年前建成的老旧小区 **12 个**，城中村 **3 处**。',
    '**工业用地：**原纺织厂、机修厂停产闲置，合计 **18.7 公顷**，是近期更新的主要空间。',
    ('h', '主要问题'),
    '**公共服务：**15 分钟生活圈内缺少中学和社区卫生服务中心，社区公共服务设施覆盖率不到一半。',
    '**居住环境：**老旧小区普遍缺少电梯、停车和无障碍设施，城中村消防通道不达标。',
    '**滨江空间：**北岸 3.6 km 岸线被厂区和仓储分隔，沿江可达的公共岸线不足三分之一。',
    ('h', '人口与建筑'),
    '**常住人口：**约 **4.2 万人**，60 岁以上人口占 **23%**，高于全市平均水平。',
    '**现状建筑：**总建筑面积 **79.0 万㎡**，2000 年前建成的占六成。',
])
tx, tw = st.col(5, 7)
rows = [['用地类型', '面积（公顷）', '比例（%）'],
        ['居住用地', 112.4, 44.7], ['公共管理与公共服务用地', 21.3, 8.5], ['商业服务业用地', 30.6, 12.2],
        ['工业用地', 18.7, 7.4], ['道路与交通设施用地', 46.9, 18.7], ['绿地与开敞空间用地', 21.3, 8.5],
        ['合计', 251.2, 100.0]]
t = p.table(tx, y0, tw, rows, [3, 1.4, 1.4], total=True, highlight=(4,))
ch = p.chart('doughnut', tx, t.bottom + 0.6, tw, y1 - t.bottom - 0.6,
             ['居住', '公服', '商业', '工业', '交通', '绿地'], [('面积', [112.4, 21.3, 30.6, 18.7, 46.9, 21.3])],
             ['title', 'secondary', 'accent', 'emphasis', 'muted', 'primary'], labels=True)

# 2. 账算式 + 流程 + 图表
q = deck.page('forecast', '3.2 更新规模测算', parent='三、更新策略与实施路径')
q.conclusion('拆除重建控制在现状建筑面积的两成以内，净增建筑面积 36.2 万㎡')
x, w = st.col(0, 7)
lg = q.ledger(x, y0, [(52.0, '新建（万㎡）', ('更新方式', '拆除重建')), '−', (15.8, '拆除（万㎡）', 'muted'), '=',
                      (36.2, '净增（万㎡）', 'emphasis')], w=(w - 2.4) / 3, h=4.2)
b = q.text(x, lg.bottom + 0.8, w, [
    ('h', '测算口径'),
    '**拆除规模：**按《关于在实施城市更新行动中防止大拆大建问题的通知》，拆除建筑面积**不大于现状总建筑面积的 20%**。',
    '**新建规模：**按片区控制性详细规划的容积率上限和公共服务设施配建要求反算。',
])
steps = ['现状评估', '更新单元划定', '实施方案编制', '分期实施']
nw, gap = (w - 3 * 1.2) / 4, 1.2
for i, s in enumerate(steps):
    nx = x + i * (nw + gap)
    q.node(nx, b.bottom + 0.8, nw, 2.4, s, ('实施时序', '近期') if i == 3 else 'title', 'node-step')
    if i:
        q.arrow(nx - gap + 0.15, b.bottom + 2.0, nx - 0.15, b.bottom + 2.0)
q.text(x, b.bottom + 4.0, w, [
    ('h', '分期安排'),
    '**近期（2026—2028 年）：**纺织厂、机修厂地块先行，拆除重建 **14.2 万㎡**，同步建设中学和社区卫生服务中心。',
    '**中期（2029—2032 年）：**北岸城中村按单元整体改造，老街片区以综合整治为主。',
    '**远期（2033—2035 年）：**滨江片区有机更新，贯通滨江绿道。',
])
cx, cw = st.col(7, 5)
ch = q.chart('column-stacked', cx, y0, cw, y1 - y0, ['北岸', '老街', '纺织厂', '滨江'],
             [('拆除重建', [8.4, 3.1, 14.2, 6.0]), ('综合整治', [6.2, 4.8, 0.0, 2.1]), ('有机更新', [3.5, 2.6, 1.2, 1.8])],
             [('更新方式', '拆除重建'), ('更新方式', '综合整治'), ('更新方式', '有机更新')], gap=60, overlap=100)

deck.save(out)
print('\n'.join(deck.warnings) or 'no warnings')
