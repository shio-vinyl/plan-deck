"""正文做法示例（docs/patterns.md）：通栏页眉预设，每种做法一页。江屿市是虚构项目，文件、数字都是编的。

用法（在仓库根目录）：
    PYTHONPATH=src .venv/bin/python examples/patterns_deck.py /tmp/patterns
    .venv/bin/python bin/plan-deck render /tmp/patterns/patterns.pptx --out /tmp/patterns/renders --engine libreoffice
"""
import os
import sys

from PIL import Image, ImageDraw

from plan_deck import Deck
from plan_deck.preset import build

out = sys.argv[1]
os.makedirs(out, exist_ok=True)

# 文件截图的替身：灰线代表文字，两段深色的是要框出的条款
doc = os.path.join(out, '文件截图示例.png')
im = Image.new('RGB', (1240, 1754), 'white')
d = ImageDraw.Draw(im)
d.rectangle((420, 90, 820, 120), fill=(90, 90, 90))
for k in range(36):
    y = 200 + k * 42
    dark = 14 <= k <= 15 or 29 <= k <= 30
    d.rectangle((110, y, 1130 if k % 6 else 900, y + 14), fill=(60, 60, 60) if dark else (165, 165, 165))
im.save(doc)

deck = Deck(build('banner'))
st = deck.style
x0, y0, x1, y1 = st.body
W = x1 - x0

# 1. 标签行 + 矩阵表 + 文件摘录
deck.chapter = '01  研究背景'
p = deck.page('process', '1.2.6 土地整备模式', parent='1.2 研究问题')
p.conclusion('土地整备须经五个环节、六类费用，流程长、政府前期投入大')
x, w = st.col(0, 7)
p.rows(x, y0, w, [
    ('申请与\n权属核实', '核实土地及地上物权属、面积、四至范围，委托测量定界，出具**测绘报告**，确认无争议、无抵押查封。'),
    ('规划与评估', '规划、自然资源部门提出规划条件、地价评估结果及开发费标准，测算收购费用、补偿和整理费用。'),
    ('方案审批', '拟定整备方案，报市土地管理委员会批准，形成区政府会议纪要。'),
    ('费用支付\n与权属变更', '按协议支付定金，完成成本审计后支付剩余款项；办理土地使用权注销登记。'),
    ('交付与出让', '纳入土地储备库，通过招标、拍卖、挂牌公开出让，**出让底价不低于评估价**。'),
])
mx, mw = st.col(7, 5)
t = p.matrix(mx, y0, mw, [['费用大类', '费用小类', ''],
                          ['征地补偿', '土地补偿费', '青苗补偿费'],
                          ['拆迁安置', '房屋拆迁补偿', '临时安置'],
                          ['土地整理', '看管与降尘', '工程费用'],
                          ['财务管理', '财务费用', '管理费用']],
             [1.3, 1.4, 1.4], merges=[(0, 1, 0, 2)], row_heads=True, bottom=y0 + 6.2)
p.excerpt(doc, mx, t.bottom + 0.35, mw, y1 - t.bottom - 0.35, crop=(0.05, 0.05, 0.95, 0.75),
          marks=[(0.07, 0.27, 0.93, 0.31), (0.07, 0.52, 0.93, 0.56)], caption='《江屿市土地整备管理办法》（江府〔2025〕8 号）摘录')

# 2. 实色栏头并列 + 实心箭头 + 结论通栏
q = deck.page('problems', '1.2.7 存在问题', parent='1.2 研究问题')
q.conclusion('基础文件到期、规则覆盖偏窄，其余情形逐案决定')
cb = q.columns(x0, y0, W, [
    ('文件到期', '**城市更新实施意见**（江府发〔2021〕6 号）：有效期五年，已到期，新文件未出台。\n'
                 '**新型产业用地暂行办法**：已到期，由修订稿接续。\n**存量盘活意见**：2026 年底到期。\n'
                 '**兼容用途比例**（江府办〔2023〕2 号）：已到期，且不含工业、仓储用地。\n'
                 '**老旧厂房改造指引**：2027 年 6 月到期，修订尚未启动。'),
    ('规则偏窄', '**城市更新细则**：面向立项入库项目，公开招标的项目不适用。\n'
                 '**控规**：按地块单一用途管理，缺少混合和转换的清单与比例。\n**社区配套**：以政府投资为主。\n'
                 '**特色资源**：滨江岸线、历史街区等用途单一，缺少复合利用的政策。\n'
                 '**公园绿地**：新增或转换经营性设施没有依据。'),
    ('逐案决定', '**闲置办公楼、低效工业用地**：主要通过修改控规和区政府决定办理。\n'
                 '**已有项目**：一事一议，同类事项每次重走论证和审批。\n**地价**：按项目单独测算。\n'
                 '**部门分工**：由规资部门牵头，审查责任由各部门分别承担。\n'
                 '**上位要求**：国家要求制定混合开发正面清单，本市尚无对应文件。'),
], head_size='figure', subs=['基础文件到期，修订未出台', '现行规则未覆盖多数存量转换', '其余情形逐案修改控规'],
    colors='类别', bottom=y1 - 2.2)
q.block_arrow((x0 + x1) / 2 - 1.2, cb.bottom + 0.12, 2.4, 0.7)
q.banner(x0, cb.bottom + 0.95, W, '需要一套事先明确、覆盖存量转换的清单和配套规则')

# 3. 粗箭头链 + 实色节点链 + 泳道
deck.chapter = '03  使用方法'
r = deck.page('flow', '3.2.1 部门分工体系', parent='3.2 使用方法')
r.conclusion('规资部门牵头办理，联审部门专业审查，区政府审定')
r.chevrons(x0, y0, W, 1.1, ['征求意见', '专家评审', '公示', ('合法性审核', 'emphasis'), ('区政府审定', 'emphasis')])
fb = r.flow(x0, y0 + 1.5, W, ['实施主体申请', '规资部门初审', ('签订变更协议', ('类别', '一')), ('补缴出让价款', ('类别', '六')),
                              ('变更登记', ('类别', '二'))], notes=[None, None, '土地处置方式', '地价补缴规则', '确权登记方式'])
r.lanes(x0, fb.bottom + 0.4, W, y1 - fb.bottom - 0.4,
        [('街道\n属地实施', ('类别', '一')), ('规资部门\n牵头办理', ('类别', '五'), 1.5), ('产业部门', ('类别', '二')),
         ('区政府', 'emphasis')],
        ['诉求收集', '申请受理', '初审会商', '联合会商', '审定', '项目监管'],
        [(0, 0, '收集诉求、指导对照'), (1, 1, '核对主体、权属、材料'), (1, (2, 3), '组织联合会商'),
         (2, 2, '审查产业准入', 'light'), (3, 4, '审定调整和规划修改', 'emphasis'), (0, 5, '签协议，全过程监管'),
         (2, 5, '认定和履约考核', 'plain')],
        links=[(0, 1), (1, 2), (2, 4), (4, 5)])

# 4. 标签方块 + 分档台阶
s = deck.page('measures', '3.3.3 功能失衡防范：措施', parent='3.3 使用方法')
s.conclusion('从编制到评估全过程防范：确定主导功能下限，记录累计量，失衡的暂停办理')
s.columns(x0, y0, W, [('编制', '街区控规写明**主导功能和分类规模容量**，确定主导功能占比下限。'),
                      ('清单', '共同前提增加一条：**不改变街区主导功能**，不突破规模容量。'),
                      ('评估', '年度评估发现功能失衡的，**调整清单或街区控规**。')], colors='类别', bottom=y0 + 2.9)
s.text(x0, y0 + 3.15, W, [('h', '过程控制和纠偏：按累计量逐级收紧')])
s.steps(x0, y0 + 4.1, W, [('未触及预警线', '按比例办理'), ('达到预警线', '后续备案项目**转清单认定**，开展片区评估'),
                          ('低于主导功能下限', '按法定程序修改控规，由审批机关从片区整体决定'),
                          ('年度评估发现失衡', '**暂停**该街区相关类型的办理，调整清单或街区控规')],
        colors='分档', h=y1 - y0 - 4.1)

path = deck.save(os.path.join(out, 'patterns.pptx'))
print(path)
for w in deck.warnings:
    print('警告：', w)
