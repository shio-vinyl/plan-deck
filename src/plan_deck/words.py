"""页面文字的用语表，inspect 和 audit 共用（docs/visual-language.md“页面绝不出现”“不当讲解员”“省略和用词”）。

BANNED 是页面绝不出现的三类，按 GIS 系列统一的清单，进 problems；其余是线索，要看上下文，只作警告。
"""
import re

# 页面绝不出现（决策 16）：免责和口径说明、待定和核查、解说和自我澄清。逐行查，备注页不查
DISCLAIM = re.compile(r'示意.{0,4}[，,：:；;]|仅供参考|(?:边界|范围|数据|位置|面积|坐标|线形|形状)[^，。\n]{0,8}以[^，。\n]{0,16}为准'
                      r'|不(?:代表|表示|作为)[^，。\n]{0,12}(?:依据|精确|准确|正式|边界|范围|结论)'
                      r'|不作[^，。\n]{0,8}依据|口径说明|经过?(?:概括|简化|示意)|未经?(?:核实|核对|校核)|精度有限')
PENDING = re.compile(r'待补|待核|待定|待确认|暂不(?:讨论|考虑|列入|确定)|官网标|状态列')
EXPLAIN = re.compile(r'不冲突|不是[^，。；\n]{0,12}的数字|^\s*(?:注|说明)[:：]|(?:本图|此图|该图)(?!斑)|图中[^，。\n]{0,8}(?:表示|代表)')
BANNED = [(DISCLAIM, '免责和口径说明'), (PENDING, '待定和核查用语'), (EXPLAIN, '解说和自我澄清')]
# 整行是数据许可署名：© 开头，或“数据来源：”“底图来源：”开头。只放行解说类（“本图据……编制”这类署名写法），后面跟了免责、待定照样报
ATTRIBUTION = re.compile(r'^\s*(?:©|(?:数据|底图)来源[:：])')

# 线索：误报多，只作警告
SPOKEN = re.compile(r'没写到|碰红线|算账|三本账|只管|走(?:规划|控规|修改|备案|程序|法定|清单|通道)|动了|不动(?!产)|补不补'
                    r'|靠(?:控规|规划|区政府)|管不到|管到')
TERSE_VERB = re.compile(r'(?<![调转变修更改确制规法决认指核约审判拟评])[转改走定补](?:商业|商务|研发|办公|居住|住宅|经营|公服|备案|比例|用途|地价|混合|类型)')


def banned(text):
    """text 里页面绝不出现的用语：[(类别, 命中的词, 所在行)]，逐行全部列出。"""
    out = []
    for line in text.splitlines():
        for rx, kind in BANNED:
            if rx is EXPLAIN and ATTRIBUTION.match(line):
                continue
            out += [(kind, m.group().strip(), line.strip()) for m in rx.finditer(line)]
    return out
